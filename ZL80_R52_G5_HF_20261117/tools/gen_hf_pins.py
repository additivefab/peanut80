"""Assign G5 signals to balls of the Hello-FPGA ZYNQ7020 core board (xc7z020clg400).
Input : sources/hellofpga/core_pins.json (parsed from the core-board schematic page 3 and connector page 12; see sources/hellofpga/README.md).
Output: interfaces/pin_review.csv, constraints/hf_core_pins_NOT_APPROVED.xdc.
Rules : Bank34 (VCCIO supplied by the carrier; 1.8 V REQUIRED for AD9268 CMOS) carries the 36 ADC data/DCO/OR lines.
        Bank35 (3.3 V on the core) carries everything else. Balls already used by the inherited G5 map stay where they are if they exist in Bank35.
        Only pins that the core brings out on its connector (page 12) are used. Clock-capable pins are kept for the two DCO and for nothing else.
The carrier-board connector pin numbers are NOT known; the signal is identified by core ball and core net name only."""
import csv,json
from pathlib import Path
R=Path(__file__).resolve().parents[1];P=json.loads((R/'sources/hellofpga/core_pins.json').read_text())
ok=[p for p in P if p['exposed'] and p['net']]
def key(p):
    n=p['net'].split('_');return (0,int(n[1][1:]),n[2]) if len(n)>2 and n[1].startswith('L') else (1,0,p['net'])
b34=sorted([p for p in ok if p['bank']=='34'],key=key);b35=sorted([p for p in ok if p['bank']=='35'],key=key)
by_ball={p['ball']:p for p in ok}
assign={};used=set()
def put(sig,p,std,note=''):
    assign[sig]=dict(p,signal=sig,std=std,note=note);used.add(p['ball'])
# ---- Bank34, 1.8 V
dco={'DCOA':'N18','DCOB':'U14'}                     # L13_P (MRCC) and L11_P (SRCC), P side
for s,b in dco.items():put(s,by_ball[b],'LVCMOS18','clock-capable P pin; DCO source-synchronous input')
free34=[p for p in b34 if not p['cc'] and p['ball'] not in used]
sigs34=[f'DA{i}' for i in range(16)]+[f'DB{i}' for i in range(16)]+['ORA','ORB']
for s,p in zip(sigs34,free34):put(s,p,'LVCMOS18','')
# ---- Bank35, 3.3 V.  keep inherited balls that exist in Bank35
inh={'ENC_M_A':'E18','ENC_M_Z':'F17','ENC_D_A':'G17','STEP':'G19','DIR':'F19','LASER_EN':'E19','EOS':'H20'}
for s,b in inh.items():
    assert b in by_ball and by_ball[b]['bank']=='35',(s,b);put(s,by_ball[b],'LVCMOS33','kept from the inherited G5 map')
rest=['SOS','ENC_M_B','ENC_D_B','ENC_D_Z','ENC_E_A','ENC_E_B','ENC_E_OPEN','MOT_EN','SHUTTER_EN','FAULT','I2C_SCL','I2C_SDA',
      'ADC_SCLK','ADC_SDIO','ADC_CSB','ADC_PDWN','TMC_UART','ENTRY_L','ENTRY_R','EXIT','ADF_READY','ADF_REQUEST']
free35=[p for p in b35 if not p['cc'] and p['ball'] not in used]
for s,p in zip(rest,free35):put(s,p,'LVCMOS33','new in this revision' if s.startswith('ENC_E') else 'moved from the inherited map')
assert len(assign)==len(dco)+len(sigs34)+len(inh)+len(rest),len(assign)
order=list(dco)+sigs34+list(inh)+rest
out=R/'interfaces/pin_review.csv'
with out.open('w',newline='',encoding='utf-8-sig') as f:
    w=csv.writer(f);w.writerow(['device','signal','ball','core_net','bank','io_standard','status','blocker'])
    for s in order:
        a=assign[s];bl='Bank34 VCCIO(1.8 V) is supplied by the carrier: not verified' if a['bank']=='34' else '底板/B05 连接器对应关系未提供；核心板网名已核对原理图'
        if s in ('ENC_E_A','ENC_E_B','ENC_E_OPEN'):bl+='；ECR-G3-01 新增'
        w.writerow(['HF_ZYNQ7020_CORE_xc7z020clg400',s,a['ball'],a['net'],'Bank'+a['bank'],a['std'],'CANDIDATE_UNAPPROVED',bl])
x=['# Candidate pin constraints for the Hello-FPGA ZYNQ7020 core (xc7z020clg400). NOT APPROVED: carrier connector, Bank34 VCCIO and level translators unverified.',
   '# Generated by tools/gen_hf_pins.py. Do not use for a bitstream until G5-HF-01..03 are closed.']
for s in order:
    a=assign[s];x.append(f'set_property -dict {{PACKAGE_PIN {a["ball"]} IOSTANDARD {a["std"]}}} [get_ports {s.lower()}]  ;# {a["net"]}')
(R/'constraints/hf_core_pins_NOT_APPROVED.xdc').write_text('\n'.join(x)+'\n')
summary={'bank34_used':sum(1 for a in assign.values() if a['bank']=='34'),'bank34_exposed':len(b34),'bank35_used':sum(1 for a in assign.values() if a['bank']=='35'),'bank35_exposed':len(b35),
         'new_encoder_e':{s:assign[s]['ball'] for s in ('ENC_E_A','ENC_E_B','ENC_E_OPEN')}}
(R/'interfaces/hf_pin_summary.json').write_text(json.dumps(summary,indent=1));print(summary)
